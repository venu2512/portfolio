#!/usr/bin/env node
// Resume gate (runs in prebuild, after optimize-photo.mjs).
// Production builds (NODE_ENV=production or CI) FAIL when public/Venugopal_V_Resume.pdf
// is missing, under 20 KB, or still contains the placeholder marker text from the old
// scripts/make-resume.mjs. In dev the same problems only warn, so local work is unblocked.
//
// The owner drops the real resume PDF (updated for the completed internship) at
// public/Venugopal_V_Resume.pdf.

import { existsSync, readFileSync, statSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const pdfPath = join(root, "public", "Venugopal_V_Resume.pdf");

const isProd = process.env.NODE_ENV === "production" || process.env.CI === "true";
const MARKERS = [
  "placeholder PDF generated by scripts/make-resume.mjs",
  "Replace public/Venugopal_V_Resume.pdf with the real resume",
];
const MIN_BYTES = 20 * 1024; // a real one-page resume PDF is never this small

const problems = [];

if (!existsSync(pdfPath)) {
  problems.push("public/Venugopal_V_Resume.pdf is missing.");
} else {
  const size = statSync(pdfPath).size;
  if (size < MIN_BYTES) {
    problems.push(`public/Venugopal_V_Resume.pdf is only ${size} bytes (< ${MIN_BYTES}) — looks like a stub.`);
  }
  // Placeholder marker check: scan the raw bytes (PDF text streams are usually
  // uncompressed or flate-encoded; the old generator wrote plain text).
  const head = readFileSync(pdfPath).subarray(0, 64 * 1024).toString("latin1");
  for (const marker of MARKERS) {
    if (head.includes(marker)) {
      problems.push(`public/Venugopal_V_Resume.pdf still contains the placeholder marker "${marker.slice(0, 40)}…".`);
      break;
    }
  }
}

if (problems.length === 0) {
  console.log("[check-resume] OK — real resume PDF found.");
  process.exit(0);
}

const message =
  "[check-resume] " +
  problems.join(" ") +
  "\n  Drop the real resume at public/Venugopal_V_Resume.pdf (same filename), then rebuild.";

if (isProd) {
  console.error(message);
  console.error("[check-resume] Failing production build (set nothing to bypass in dev).");
  process.exit(1);
}

console.warn(message);
console.warn("[check-resume] Dev build continuing with the placeholder PDF.");
process.exit(0);
